/* Description
某公司有个工厂和仓库。由于原材料等价格波动，工厂每个月的生产成本也会波动，令第𝑖个月产品的单位生产成本为𝑐_𝑖（该月生产一个产品的成本为𝑐_𝑖）。
仓库储存产品的也有成本，假设每个月产品的单位储存成本为固定值1（存储一个产品一个月的成本为1）。
令第𝑖个月需要供应给客户的产品数量为𝑦_𝑖，仓库里的和生产的产品均可供应给客户。
假设仓库的容量无限大，供应给客户剩余的产品可储存在仓库中。
若已知𝑛个月中各月的单位生产成本𝑐_𝑖、以及产品供应量𝑦_𝑖，设计一算法决策每个月的产品生产数量𝑥_𝑖，使得𝑛个月的总成本最低。

例如：𝑛=3，𝑐_𝑖:2,5,3，𝑦_𝑖:2,4,5，则𝑥_𝑖:6,0,5，即第1个月生产6个供应2个（代价2×2=4），储存4个供应给第2个月（代价(2+1)×4=12），第3个月生产5个供应5个（代价3×5=15），使总成本4+12+15=31最小。
*/

// Input
// 第一行输入T(T<=10)表示有T组数据。每组数据先输入一个正整数N(1<=N<=100000)，表示共有N个月，接下来输入两行每行N个数，分别表示每个月的成本c_i以及产品需求量y_i。输入保证所有数据均在int范围内。

// Output
// 输出T行正整数，第i行表示第i组数据下的最小成本。(输出不保证不溢出int)

// Sample Input
// 1
// 3
// 2 5 3
// 2 4 5

// Sample Output
// 31

/*
算法说明：贪心类
①算法思想
对第i个月的需求，只需要知道“到这个月为止，生产并储存到本月的最低单位成本”。
每个月更新cost = min(本月生产成本c[i], 上月最优成本cost + 1)，
然后用该最低成本满足本月需求。

②伪代码
MinProductionCost(c, y):
    cost = c[1]
    ans = cost * y[1]
    for i = 2 to n:
        cost = min(c[i], cost + 1)
        ans = ans + cost * y[i]
    return ans

③如何根据子问题最优确定总问题最优
如果某个月以前的产品储存到当前月比当前生产更便宜，就继续使用这个来源；
否则从当前月重新生产。当前月需求的选择只依赖此前能到达当前月的最低单位成本，
该局部最优不会影响未来，因为未来只需要把这个最低成本再加储存费继续比较。
所以逐月更新即可得到总成本最优。
*/

#include <algorithm>
#include <iostream>
#include <vector>
using namespace std;

