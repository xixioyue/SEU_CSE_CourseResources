// 和现有代码的最大区别在于现有代码中每个月的生产成本是基于上个月的生产成本进行转移的，而暴力枚举方式中每个月的生产成本是基于当月的生产成本进行转移的。
// 由于每个月的生产成本是基于上个月的生产成本进行转移的，所以现有代码的时间复杂度为O(n)，而暴力枚举方式的时间复杂度为O(n^2)。

// 如果要记录每个月生产的产品数量，可以增加一个数组记录第i个月的产品应该在第几个月生产
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int T;
    if (!(cin >> T)) return 0;
    while (T--) {
        int n;
        cin >> n;
        
        vector<long long> c(n), y(n);
        for (int i = 0; i < n; ++i) cin >> c[i]; // 生产成本
        for (int i = 0; i < n; ++i) cin >> y[i]; // 产品需求量

        long long cost = c[0]; // 最优生产成本
        long long ans = 0; // 总成本

        // 转移
        ans += cost * y[0];
        for (int i=1; i<n; ++i){
            cost = min(c[i], cost + 1);
            ans += cost * y[i];
        }
        
        cout << ans << '\n';
    }
    return 0;
}